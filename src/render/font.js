// 3x5 bitmap font, rows top to bottom. '*' is a heart.
const GLYPHS = {
  A: '111101111101101', B: '110101110101110', C: '011100100100011', D: '110101101101110',
  E: '111100110100111', F: '111100110100100', G: '011100101101011', H: '101101111101101',
  I: '111010010010111', J: '111001001101010', K: '101101110101101', L: '100100100100111',
  M: '101111111101101', N: '110101101101101', O: '010101101101010', P: '110101110100100',
  Q: '010101101110011', R: '110101110101101', S: '011100010001110', T: '111010010010010',
  U: '101101101101111', V: '101101101101010', W: '101101111111101', X: '101101010101101',
  Y: '101101010010010', Z: '111001010100111',
  0: '111101101101111', 1: '010110010010111', 2: '110001010100111', 3: '110001010001110',
  4: '101101111001001', 5: '111100110001110', 6: '011100111101111', 7: '111001010010010',
  8: '111101111101111', 9: '111101111001110',
  ' ': '000000000000000', '.': '000000000000010', ',': '000000000010100', '!': '010010010000010',
  '?': '110001010000010', ':': '000010000010000', '-': '000000111000000', '+': '000010111010000',
  '/': '001001010100100', "'": '010010000000000', '(': '010100100100010', ')': '010001001001010',
  '<': '001010100010001', '>': '100010001010100', '^': '010101000000000', '*': '000101111010000',
};

export const textWidth = (s, scale = 1) => (String(s).length * 4 - 1) * scale;

function raw(ctx, s, x, y, color, scale) {
  ctx.fillStyle = color;
  for (let i = 0; i < s.length; i++) {
    const g = GLYPHS[s[i]];
    if (!g) continue;
    const gx = x + i * 4 * scale;
    for (let k = 0; k < 15; k++) {
      if (g[k] === '1') ctx.fillRect(gx + (k % 3) * scale, y + Math.floor(k / 3) * scale, scale, scale);
    }
  }
}

export function drawText(ctx, s, x, y, color, { scale = 1, shadow = null, align = 'left' } = {}) {
  s = String(s).toUpperCase();
  const w = textWidth(s, scale);
  if (align === 'center') x -= Math.floor(w / 2);
  else if (align === 'right') x -= w;
  x = Math.round(x);
  y = Math.round(y);
  if (shadow) raw(ctx, s, x, y + scale, shadow, scale);
  raw(ctx, s, x, y, color, scale);
}
